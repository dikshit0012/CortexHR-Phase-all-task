"""Run example messages through the SAME ChatService the /v1/chat endpoint uses and write reports/example_conversations.md.
Every number and reply in that file is produced by this run (nothing is typed by hand).   Run from the `task 9` folder."""
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from cortexhr_task9.chat_service import load_chat_service  # noqa: E402
from cortexhr_task9.paths import REPORTS  # noqa: E402

MAIN = [
    ("1. Supported HR question", "How long is the notice period?",
     "A clear, well-formed question that matches a trained intent and an approved FAQ answer."),
    ("2. Informal / messy question", "whn is salary credited yaar",
     "Slang and a typo ('whn'). The cleaner and the character n-grams cope; the answer is the approved salary-payment-day FAQ."),
    ("3. Unsupported question", "what is the dress code",
     "A genuine HR topic (FAQ-29 exists) but NO intent in the training data covers it, so the classifier is unsure and the bot refuses instead of guessing."),
]
EXTRA = ["wat r the office timings", "how many sick leaves do I get?", "do we work on saturdays", "can I bring my dog to the office",
         "how is LOP calculated", "show my payslip for June", "hello"]


def run(svc, message):
    r = svc.reply(message)
    body = {"intent": r.intent, "confidence": r.confidence, "reply": r.reply, "fallback": r.fallback}
    return r, body


def main() -> None:
    svc = load_chat_service()
    out = ["# Example conversations (real runs)", "",
           f"Generated by `scripts/make_example_conversations.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC with model "
           f"`{svc.model.version}`, confidence threshold **{svc.threshold}**. The JSON blocks are exactly what `POST /v1/chat` returns for "
           "each message (same `ChatService`). `confidence` is the classifier's top probability, not a calibrated probability.", ""]
    for title, msg, why in MAIN:
        r, body = run(svc, msg)
        out += [f"## {title}", "", f"**User:** {msg}", "", "```json", json.dumps(body, indent=2), "```", "",
                f"- Predicted intent: `{r.intent}`" if r.intent else "- Predicted intent: none returned (below threshold)",
                f"- Confidence: {r.confidence}", f"- Fallback triggered: {'yes' if r.fallback else 'no'} (reason code: `{r.reason}`)",
                f"- FAQ entries used: {', '.join(r.faq_ids) if r.faq_ids else 'none'}", f"- Why: {why}", ""]
    out += ["## Other messages tried with the same build (not selected for being good)", "",
            "| message | intent | confidence | fallback | reason | reply (start) |", "|---|---|---|---|---|---|"]
    for msg in EXTRA:
        r, _ = run(svc, msg)
        out.append(f"| {msg} | {r.intent} | {r.confidence} | {r.fallback} | {r.reason} | {r.reply[:70].replace('|', '/')} |")
    out += ["", "Note how natural FAQ wordings such as 'how many sick leaves do I get?' and 'do we work on saturdays' fall below the "
            "threshold: the model was trained on only ~6 distinct phrasings per intent. See README 'Known limitations'."]
    (REPORTS / "example_conversations.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
