def _candidates():
    env = os.environ.get("CORTEXHR_TASK13_ROOT")
    if env:
        yield Path(env).expanduser()
    for name in ("task 13", "task13", "task_13", "Task 13"):
        yield REPO_ROOT / name


def locate_task13_root() -> Path:
    for c in _candidates():
        if (c / "src" / "attrition_v2").is_dir() and (c / "model_artifacts" / MODEL_VERSION / "model.joblib").is_file():
            return c
    raise FileNotFoundError("Cannot find Task 13 (folder containing src/attrition_v2 and model_artifacts/attrition-v2/model.joblib). "
                            "Set CORTEXHR_TASK13_ROOT.")


def locate_cortexhr_src() -> Path | None:
    env = os.environ.get("CORTEXHR_ML_SRC")
    if env and (Path(env) / "cortexhr").is_dir():
        return Path(env).resolve()
    candidates = [
        REPO_ROOT.parent / "phase-1" / "task04" / "src",
        REPO_ROOT / "task 4" / "files" / "cortexhr-ml" / "src",
        REPO_ROOT.parent / "Phase 1 All task" / "task 4" / "files" / "cortexhr-ml" / "src",
        REPO_ROOT.parent / "Phase 1 All task" / "task 1" / "cortexhr-ml" / "src",
        REPO_ROOT.parent / "CortexHR--master (1)" / "CortexHR--master" / "task 4" / "files" / "cortexhr-ml" / "src",
        REPO_ROOT.parent / "task 4" / "files" / "cortexhr-ml" / "src",
        REPO_ROOT / "cortexhr-ml" / "src",
    ]
    for c in candidates:
        if (c / "cortexhr").is_dir():
            return c.resolve()
    return None


def locate_workbook(cortexhr_src: Path | None = None) -> Path | None:
    env = os.environ.get("CORTEXHR_WORKBOOK")
    if env and Path(env).is_file():
        return Path(env).resolve()
    candidates = []
    if cortexhr_src:
        candidates.extend([
            cortexhr_src.parent / "data" / "raw" / "02_CortexHR_AI_ML_Dataset.xlsx",
            cortexhr_src.parent / "data" / "raw" / "CortexHR_Dataset.xlsx",
        ])
    candidates.extend([
        REPO_ROOT.parent / "Phase 1 All task" / "task 4" / "files" / "cortexhr-ml" / "data" / "raw" / "02_CortexHR_AI_ML_Dataset.xlsx",
        REPO_ROOT.parent / "Phase 1 All task" / "task 5" / "data" / "raw" / "02_CortexHR_AI_ML_Dataset.xlsx",
        REPO_ROOT.parent / "CortexHR Phase 2" / "task 5" / "data" / "raw" / "02_CortexHR_AI_ML_Dataset.xlsx",
    ])
    for c in candidates:
        if c.is_file():
            return c.resolve()
    return None


def ensure_task13_importable() -> Path:
    if "CORTEXHR_ML_SRC" not in os.environ:
        c_src = locate_cortexhr_src()
        if c_src:
            os.environ["CORTEXHR_ML_SRC"] = str(c_src)
    if "CORTEXHR_WORKBOOK" not in os.environ:
        src_path = Path(os.environ["CORTEXHR_ML_SRC"]) if "CORTEXHR_ML_SRC" in os.environ else None
        wb = locate_workbook(src_path)
        if wb:
            os.environ["CORTEXHR_WORKBOOK"] = str(wb)
    root = locate_task13_root()
    if str(root / "src") not in sys.path:
        sys.path.insert(0, str(root / "src"))
    return root
